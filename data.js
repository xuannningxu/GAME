export function validAnswers(a){return Array.isArray(a)&&a.length===24&&Array.from(a).every(v=>Number.isInteger(v)&&v>=0&&v<=3);}
export function encodeResult(a){if(!validAnswers(a))throw new Error('无效答案');return '#v1='+a.join('');}
export function decodeResult(hash){if(!/^#v1=[0-3]{24}$/.test(hash))return null;return [...hash.slice(4)].map(Number);}
export function score(a){
 if(!validAnswers(a)) throw new Error('需要24个有效答案');
 const vector=dimensions.map((_,d)=>questions.reduce((s,q,i)=>s+(q.dim===d?q.values[a[i]]:0),0)/4);
 const ranked=animals.map((animal,index)=>({animal,index,distance:Math.sqrt(animal.vector.reduce((s,v,i)=>s+(v-vector[i])**2,0)/6)})).sort((a,b)=>a.distance-b.distance||a.index-b.index);
 return {vector,ranked};
}
